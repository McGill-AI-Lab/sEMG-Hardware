/*
 * =============================================================================
 *  ads1298.h  —  Low-level driver for the TI ADS1298 (the "what")
 * =============================================================================
 *
 *  WHAT IS A HEADER FILE?
 *  ----------------------
 *  In C/C++ code is usually split into two files:
 *    - a header  (.h)   that DECLARES what exists: constants, function names,
 *                       their parameters and return types;
 *    - a source  (.cpp) that DEFINES how each function actually works.
 *  Any other file that wants to use the driver writes  #include "ads1298.h"
 *  and the compiler then knows the names and types. The linker later connects
 *  the calls to the real code in ads1298.cpp.
 *
 *  WHAT THIS DRIVER DOES
 *  ---------------------
 *  It hides the details of talking to the ADS1298 over SPI:
 *    - power-up and reset sequence,
 *    - sending one-byte commands (START, STOP, RDATAC, SDATAC ...),
 *    - reading and writing configuration registers,
 *    - reading one 27-byte data frame after each conversion,
 *    - counting DRDY ("data ready") pulses in an interrupt.
 *
 *  HOW THE ADS1298 TALKS TO THE ESP32 (big picture)
 *  ------------------------------------------------
 *
 *     ESP32-S3                         ADS1298
 *     --------                         -------
 *     SCLK  (GPIO18) ───────────────►  SCLK    serial clock, generated by the ESP32
 *     MOSI  (GPIO17) ───────────────►  DIN     data ESP32 -> ADS (commands, register values)
 *     MISO  (GPIO19) ◄───────────────  DOUT    data ADS -> ESP32 (register values, samples)
 *     CS    (GPIO16) ───────────────►  CS      "chip select": LOW = "I am talking to you"
 *     START (GPIO12) ───────────────►  START   HIGH = keep converting
 *     PWDN  (GPIO7)  ───────────────►  PWDN    LOW = power down the chip
 *     RST   (GPIO6)  ───────────────►  RESET   LOW pulse = reset all registers
 *     DRDY  (GPIO15) ◄───────────────  DRDY    falls LOW each time a new sample is ready
 *
 *  SPI is a "synchronous" bus: on each clock edge one bit goes out on MOSI and
 *  one bit comes back on MISO at the same time. So every SPI.transfer(x)
 *  both SENDS byte x and RETURNS the byte that the ADS1298 sent back.
 *
 *  Datasheet: TI SBAS459 "ADS129x Low-Power, 8-Channel, 24-Bit AFE".
 * =============================================================================
 */
#pragma once                       // tell the compiler to include this file only once per build, even if #included twice

#include <Arduino.h>               // Arduino core: pinMode, digitalWrite, delay, uint8_t, ...
#include <SPI.h>                   // Arduino SPI library: SPIClass, SPISettings, SPI.transfer(...)

/*
 * -----------------------------------------------------------------------------
 *  PIN ASSIGNMENT
 * -----------------------------------------------------------------------------
 *  These are the ESP32-S3 GPIO numbers wired to the ADS1298 on your board.
 *  They are the same numbers used by the earlier internal_wg_test sketch and
 *  the ADS1298_diagnostic sketch, so no rewiring is needed.
 *  "constexpr" means "a constant known at compile time": it costs no RAM and
 *  the compiler substitutes the number wherever the name is used.
 * -----------------------------------------------------------------------------
 */
constexpr int PIN_SCLK  = 18;      // SPI clock output to ADS1298 SCLK
constexpr int PIN_MISO  = 19;      // SPI data input  <- ADS1298 DOUT
constexpr int PIN_MOSI  = 17;      // SPI data output -> ADS1298 DIN
constexpr int PIN_CS    = 16;      // chip select, driven by hand (LOW while talking)
constexpr int PIN_START = 12;      // START pin: HIGH = conversions run, LOW = stopped
constexpr int PIN_PWDN  = 7;       // power-down pin: LOW = chip powered down
constexpr int PIN_RST   = 6;       // reset pin: a LOW pulse resets the chip
constexpr int PIN_DRDY  = 15;      // data-ready input: falls LOW when a new frame is ready

/*
 * -----------------------------------------------------------------------------
 *  DATA-READY SOURCE: the DRDY pin, or DOUT standing in for it
 * -----------------------------------------------------------------------------
 *  Normally the ADS1298 tells us "a new frame is ready" by pulling its DRDY
 *  pin (TQFP pin 47) LOW, and we catch that on GPIO15.
 *
 *  On the clamshell (2026-11-15) DRDY does not reach GPIO15: the chip was
 *  shown to convert (RDATA reads changed, test signal visible) but GPIO15
 *  only ever followed the ESP32's own pull-up / pull-down resistor.
 *
 *  Workaround from the datasheet (RDATAC section): "If no data are retrieved
 *  from the device, DOUT and DRDY behave similarly in this mode." So while CS
 *  is held LOW, the DOUT line (already wired, it is our MISO on GPIO19) falls
 *  at every new conversion, exactly like DRDY. We put the DRDY interrupt on
 *  GPIO19 instead and switch it off while we clock a frame out (our own
 *  reading makes DOUT toggle 216 times, those edges must not be counted).
 *  Measured on this board: exactly one edge per conversion at 500, 2000 and
 *  4000 SPS, every interval within +/-10 % of the sample period.
 *
 *  true  = use DOUT (workaround, needed while the DRDY wire is open)
 *  false = use the real DRDY pin on GPIO15 (once the wiring is fixed)
 *  PING reports which one is active ("drdy=dout" / "drdy=pin"), and the PC
 *  saves it in device.json of every run.
 * -----------------------------------------------------------------------------
 */
constexpr bool DRDY_VIA_DOUT = true;

/*
 * -----------------------------------------------------------------------------
 *  FRAME AND PACKET SIZES
 * -----------------------------------------------------------------------------
 *  After every conversion the ADS1298 offers one "frame" on DOUT:
 *      3 bytes status word  +  8 channels x 3 bytes (24-bit samples) = 27 bytes
 *  (datasheet, "Data Output Protocol"). Powered-down channels still occupy
 *  their 3 bytes, so the frame size never changes.
 *
 *  We forward each frame to the PC inside a small "packet" (see main.cpp):
 *      2 sync bytes + 4 byte sequence number + 27 byte frame + 1 checksum = 34
 *  The PC side (host/clamshell/device.py) uses exactly the same numbers.
 * -----------------------------------------------------------------------------
 */
constexpr int ADS_CHANNELS    = 8;                              // ADS1298 has 8 input channels
constexpr int ADS_FRAME_BYTES = 3 + ADS_CHANNELS * 3;           // 3 status + 24 channel bytes = 27
constexpr int PACKET_BYTES    = 2 + 4 + ADS_FRAME_BYTES + 1;    // sync + seq + frame + checksum = 34
constexpr uint8_t PACKET_SYNC0 = 0xA5;                          // first sync byte (an unlikely bit pattern: 10100101)
constexpr uint8_t PACKET_SYNC1 = 0x5A;                          // second sync byte (its inverse: 01011010)

/*
 * -----------------------------------------------------------------------------
 *  ADS1298 SPI COMMANDS  (datasheet, "SPI Command Definitions")
 * -----------------------------------------------------------------------------
 *  Every command is a single "opcode" byte sent while CS is LOW.
 *  RREG and WREG are special: their low 5 bits carry a register address and
 *  they are followed by more bytes (see adsReadRegisters / adsWriteRegister).
 * -----------------------------------------------------------------------------
 */
constexpr uint8_t CMD_WAKEUP  = 0x02;   // leave standby mode
constexpr uint8_t CMD_STANDBY = 0x04;   // enter low-power standby
constexpr uint8_t CMD_RESET   = 0x06;   // software reset (same effect as the RST pin)
constexpr uint8_t CMD_START   = 0x08;   // start conversions (we use the START *pin* instead, see below)
constexpr uint8_t CMD_STOP    = 0x0A;   // stop conversions
constexpr uint8_t CMD_RDATAC  = 0x10;   // Read DATA Continuous: frames appear on DOUT after every DRDY
constexpr uint8_t CMD_SDATAC  = 0x11;   // Stop read DATA Continuous: needed before any register access
constexpr uint8_t CMD_RDATA   = 0x12;   // read one frame on demand (not used here)
constexpr uint8_t CMD_RREG    = 0x20;   // 001r rrrr : read registers starting at address r rrrr
constexpr uint8_t CMD_WREG    = 0x40;   // 010r rrrr : write registers starting at address r rrrr

/*
 * -----------------------------------------------------------------------------
 *  ADS1298 REGISTER ADDRESSES  (datasheet, "Register Map")
 * -----------------------------------------------------------------------------
 *  Registers are 8-bit memory cells inside the chip that hold its settings.
 *  We only list the ones this firmware touches by name. The PC decides the
 *  VALUES (see host/clamshell/ads1298.py); the firmware just writes them.
 * -----------------------------------------------------------------------------
 */
constexpr uint8_t REG_ID      = 0x00;   // read-only device ID (ADS1298 = 0x92)
constexpr uint8_t REG_CONFIG1 = 0x01;   // HR/LP mode, daisy-chain, clock out, data rate
constexpr uint8_t REG_CONFIG2 = 0x02;   // internal test-signal source, amplitude, frequency
constexpr uint8_t REG_CONFIG3 = 0x03;   // reference buffer, reference voltage, RLD settings
constexpr uint8_t REG_CH1SET  = 0x05;   // channel 1 settings (power-down, gain, input MUX)
constexpr uint8_t REG_CH8SET  = 0x0C;   // channel 8 settings (CH2SET..CH7SET are 0x06..0x0B)
constexpr uint8_t REG_CONFIG4 = 0x17;   // single-shot vs continuous, lead-off comparator power
constexpr uint8_t REG_COUNT   = 0x1A;   // total number of registers (0x00 .. 0x19 = 26)

/*
 * -----------------------------------------------------------------------------
 *  NUMBER OF CONFIGURABLE REGISTERS SENT BY THE PC
 * -----------------------------------------------------------------------------
 *  The PC's "CFG" command carries 12 values, always in this order:
 *     CONFIG1, CONFIG2, CONFIG3, CONFIG4, CH1SET, CH2SET, ..., CH8SET
 * -----------------------------------------------------------------------------
 */
constexpr int CFG_VALUE_COUNT = 12;     // 4 CONFIG registers + 8 CHnSET registers

/*
 * -----------------------------------------------------------------------------
 *  FUNCTION DECLARATIONS
 * -----------------------------------------------------------------------------
 *  Each function is fully explained in ads1298.cpp, right above its code.
 *  Here we only list them so main.cpp can call them.
 * -----------------------------------------------------------------------------
 */
void     adsBegin();                                             // set up pins + SPI, power up and reset the chip
void     adsPowerCycle();                                        // PWDN low/high + reset: all registers back to defaults
void     adsCommand(uint8_t cmd);                                // send a single-byte command
void     adsWriteRegister(uint8_t reg, uint8_t value);           // write one register
uint8_t  adsReadRegister(uint8_t reg);                           // read one register
void     adsReadRegisters(uint8_t first, uint8_t count, uint8_t *out);  // read several consecutive registers
bool     adsApplyConfig(const uint8_t values[CFG_VALUE_COUNT],
                        uint8_t readback[CFG_VALUE_COUNT]);      // write the 12 settings, read them back
void     adsStartConversions();                                  // RDATAC + START pin HIGH
void     adsStopConversions();                                   // START pin LOW + SDATAC
void     adsReadFrame(uint8_t *frame);                           // clock out one 27-byte frame
void     adsSetDataClock(uint32_t hz);                           // choose the SPI clock used for frame reads
uint32_t adsGetDataClock();                                      // report the current frame-read SPI clock
void     adsDrdySnapshot(uint32_t &count, int64_t &timeUs);      // safely copy the DRDY counter + timestamp
uint32_t adsNominalPeriodUs();                                   // sample period (us) of the data rate last written to CONFIG1
